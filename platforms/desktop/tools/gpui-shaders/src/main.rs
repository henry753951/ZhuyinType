//! Compiles GPUI's Windows shaders (vendor/gpui-pre-windows/src/shaders.hlsl) to Direct3D bytecode, as the upstream
//! build script does with `fxc /O3`, and writes them as Rust constants for `shaders/shaders_bytes.rs`.  It runs on
//! Windows, where d3dcompiler_47.dll (the compiler fxc uses) is part of the system; release builds cross-compiled on
//! Linux then use the result.
//!
//!   gpui-shaders.exe PATH\TO\shaders.hlsl > shaders_bytes.rs

const MODULES: [&str; 8] = [
    "quad",
    "shadow",
    "path_rasterization",
    "path_sprite",
    "underline",
    "monochrome_sprite",
    "subpixel_sprite",
    "polychrome_sprite",
];

/// FNV-1a (64-bit) of shaders.hlsl and alpha_correction.hlsl, carriage returns ignored; the vendored build script
/// checks it.
fn source_hash(shaders: &std::path::Path) -> std::io::Result<u64> {
    let mut hash: u64 = 0xcbf2_9ce4_8422_2325;
    for path in [shaders.to_path_buf(), shaders.with_file_name("alpha_correction.hlsl")] {
        for byte in std::fs::read(path)?.into_iter().filter(|&byte| byte != b'\r') {
            hash ^= u64::from(byte);
            hash = hash.wrapping_mul(0x0100_0000_01b3);
        }
    }
    Ok(hash)
}

#[cfg(windows)]
fn compile(path: &std::path::Path, entry: &str, target: &str) -> Result<Vec<u8>, String> {
    use windows::Win32::Graphics::Direct3D::{
        Fxc::D3DCOMPILE_OPTIMIZATION_LEVEL3, Fxc::D3DCompileFromFile, ID3DBlob, ID3DInclude,
    };
    use windows::Win32::Graphics::Hlsl::D3D_COMPILE_STANDARD_FILE_INCLUDE;
    use windows::core::{HSTRING, PCSTR};

    let entry = format!("{entry}\0");
    let target = format!("{target}\0");
    let mut code: Option<ID3DBlob> = None;
    let mut errors: Option<ID3DBlob> = None;
    // SAFETY: NUL-terminated strings; the standard include handler is the documented sentinel pointer value.
    unsafe {
        let include = std::mem::transmute::<usize, ID3DInclude>(D3D_COMPILE_STANDARD_FILE_INCLUDE as usize);
        let result = D3DCompileFromFile(
            &HSTRING::from(path.as_os_str()),
            None,
            &include,
            PCSTR(entry.as_ptr()),
            PCSTR(target.as_ptr()),
            D3DCOMPILE_OPTIMIZATION_LEVEL3,
            0,
            &mut code,
            Some(&mut errors),
        );
        if let Err(error) = result {
            let message = errors.map(|blob| {
                let bytes = std::slice::from_raw_parts(blob.GetBufferPointer().cast::<u8>(), blob.GetBufferSize());
                String::from_utf8_lossy(bytes).into_owned()
            });
            return Err(format!("{error}: {}", message.unwrap_or_default()));
        }
        let code = code.ok_or("no bytecode")?;
        Ok(std::slice::from_raw_parts(code.GetBufferPointer().cast::<u8>(), code.GetBufferSize()).to_vec())
    }
}

#[cfg(windows)]
fn main() -> Result<(), String> {
    use std::fmt::Write as _;
    let path = std::env::args().nth(1).ok_or("usage: gpui-shaders PATH\\TO\\shaders.hlsl")?;
    let path = std::fs::canonicalize(&path).map_err(|error| format!("{path}: {error}"))?;
    let hash = source_hash(&path).map_err(|error| error.to_string())?;
    let mut out = String::new();
    out.push_str(
        "// Generated by platforms/desktop/tools/gpui-shaders from src/shaders.hlsl (D3DCompile, /O3). Do not edit.\n",
    );
    let _ = writeln!(out, "// source-fnv1a64: {hash:016x}");
    for module in MODULES {
        for (stage, target, name) in [("vertex", "vs_4_1", "VERTEX"), ("fragment", "ps_4_1", "FRAGMENT")] {
            let bytes = compile(&path, &format!("{module}_{stage}"), target)?;
            let list = bytes.iter().map(|byte| format!("{byte:#04x}")).collect::<Vec<_>>().join(", ");
            let _ = writeln!(out, "const {}_{name}_BYTES: &[u8] = &[{list}];", module.to_uppercase());
        }
    }
    print!("{out}");
    Ok(())
}

#[cfg(not(windows))]
fn main() {
    let _ = (MODULES, source_hash);
    eprintln!("gpui-shaders runs on Windows (it uses the system's d3dcompiler_47.dll)");
    std::process::exit(2);
}
